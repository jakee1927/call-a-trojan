"use client";
import { useEffect, useRef, useState } from "react";
import { Markdown } from "./Markdown";

export function GapReport({ initial }: { initial: { body_md: string; created_at: string; handoff_count: number } | null }) {
  const [report, setReport] = useState(initial);
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState<string | null>(null);
  async function gen(auto = false) {
    setBusy(true);
    setErr(null);
    try {
      const r = await fetch("/api/insights/gap", { method: "POST" });
      const d = await r.json().catch(() => ({}));
      if (!r.ok) {
        if (!auto) setErr(d.error ?? "Couldn't generate the report");
        return;
      }
      setReport(d.report);
    } finally {
      setBusy(false);
    }
  }
  // No report yet: write the first one automatically from the handoff log.
  const tried = useRef(false);
  useEffect(() => {
    if (!initial && !tried.current) {
      tried.current = true;
      gen(true);
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);
  return (
    <div className="rounded-3xl bg-ink p-6 text-white md:p-8">
      <div className="flex flex-wrap items-start gap-3">
        <div>
          <div className="text-[11px] font-bold uppercase tracking-[0.2em] text-gold">Auto-generated by AI from the handoff log</div>
          <h2 className="mt-1 text-2xl font-black md:text-3xl">Questions USC&apos;s websites can&apos;t answer</h2>
        </div>
        <button onClick={() => gen()} disabled={busy} className="ml-auto rounded-full bg-gold px-4 py-2 text-sm font-black text-cardinal disabled:opacity-60">
          {busy ? "Reading the log…" : report ? "Regenerate" : "Generate report"}
        </button>
      </div>
      {err && <p className="mt-3 text-sm text-gold">{err}</p>}
      {report ? (
        <div className="mt-5 rounded-2xl bg-white p-5 text-ink">
          <Markdown text={report.body_md} sources={[]} />
          <p className="mt-3 text-xs text-black/40">
            From {report.handoff_count} handed-off questions · {new Date(report.created_at).toLocaleString("en-US", { timeZone: "America/Los_Angeles" })}
          </p>
        </div>
      ) : (
        <p className="mt-4 text-white/60">
          {busy ? "Writing the first report from every question our AI had to hand to a Trojan…" : "No report yet. Generate one from every question our AI had to hand to a Trojan."}
        </p>
      )}
    </div>
  );
}
